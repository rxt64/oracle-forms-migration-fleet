    [GeneratedRegex(@"\bCREATE\s+(?:OR\s+REPLACE\s+)?(?:EDITIONABLE\s+|NONEDITIONABLE\s+)?PACKAGE\b", RegexOptions.CultureInvariant)]
    private static partial Regex PackagePattern();

    [GeneratedRegex(@"\bPROCEDURE\b", RegexOptions.CultureInvariant)]
    private static partial Regex ProcedurePattern();

    [GeneratedRegex(@"\bFUNCTION\b", RegexOptions.CultureInvariant)]
    private static partial Regex FunctionPattern();

    [GeneratedRegex(@"\bCREATE\s+(?:OR\s+REPLACE\s+)?TRIGGER\b", RegexOptions.CultureInvariant)]
    private static partial Regex TriggerPattern();

    [GeneratedRegex(@"%ROWTYPE", RegexOptions.CultureInvariant)]
    private static partial Regex RowTypePattern();

    [GeneratedRegex(@"\bCONNECT\s+BY\b", RegexOptions.CultureInvariant)]
    private static partial Regex ConnectByPattern();

    [GeneratedRegex(@"\bFROM\s+DUAL\b", RegexOptions.CultureInvariant)]
