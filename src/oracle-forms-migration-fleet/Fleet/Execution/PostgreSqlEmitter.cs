namespace OracleFormsMigrationFleet.Fleet.Execution;

/// <summary>How much human work a converted construct still needs.</summary>
public enum ConversionSeverity
{
    /// <summary>Converted faithfully; recorded so the mapping stays auditable.</summary>
    Note,

    /// <summary>Converted, but Oracle and PostgreSQL semantics are not guaranteed to agree.</summary>
    ManualReview,

    /// <summary>Not converted at all. A human has to rewrite it.</summary>
    Unsupported,
}

public sealed record ConversionFinding(
    ConversionSeverity Severity,
    string Category,
    string Construct,
    string Reason);

public sealed record TypeMapping(string Table, string Column, string OracleType, string PostgreSqlType);

public sealed record ConversionReport(
    int Tables,
    int Columns,
    int Constraints,
    int Sequences,
    int Indexes,
    IReadOnlyList<TypeMapping> TypeMappings,
    IReadOnlyList<ConversionFinding> Findings);

public sealed record PostgreSqlConversion(string Ddl, ConversionReport Report);

/// <summary>
/// Converts a parsed Oracle schema to PostgreSQL DDL. Pure: no file, process, or network access, and no
/// timestamp is embedded in the generated SQL so repeated runs over the same input are byte-identical.
/// PL/SQL bodies are never translated; they are reported as manual PL/pgSQL rewrites.
/// </summary>
public static partial class PostgreSqlEmitter
{
    private static readonly HashSet<string> s_reserved = new(StringComparer.Ordinal)
