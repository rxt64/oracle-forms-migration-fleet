/// <summary>
/// Emits the React and TypeScript master/detail screen over the generated API.
///
/// The screen is generated from roles, so its shape does not depend on what the estate's tables are
/// called. Headings and column labels are derived from the mapped identifiers, which is presentation; no
/// rule, validation, or route is chosen from a name. Nothing computed in the browser is authoritative:
/// the line preview is labelled as a preview and the stored total comes back from the server.
/// </summary>
internal static class DotNetFrontendEmitter
{
